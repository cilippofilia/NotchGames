/// A small 5×7 dot-matrix font, just the letters the app shows. `#` is a lit dot.
nonisolated enum PixelFont {
    static let height = 7

    static let glyphs: [Character: [String]] = [
        "h": ["#....", "#....", "#.##.", "##..#", "#...#", "#...#", "#...#"],
        "e": [".....", ".....", ".###.", "#...#", "#####", "#....", ".###."],
        "l": [".##..", "..#..", "..#..", "..#..", "..#..", "..#..", ".###."],
        "o": [".....", ".....", ".###.", "#...#", "#...#", "#...#", ".###."],
        "t": [".#...", ".#...", "###..", ".#...", ".#...", ".#..#", "..##."],
        "r": [".....", ".....", "#.##.", "##..#", "#....", "#....", "#...."],
        "i": ["..#..", ".....", ".##..", "..#..", "..#..", "..#..", ".###."],
        "n": [".....", ".....", "#.##.", "##..#", "#...#", "#...#", "#...#"],
        "c": [".....", ".....", ".###.", "#....", "#....", "#...#", ".###."],
        "g": [".....", ".....", ".####", "#...#", ".####", "....#", ".###."],
        "a": [".....", ".....", ".###.", "....#", ".####", "#...#", ".####"],
        "m": [".....", ".....", "##.#.", "#.#.#", "#.#.#", "#...#", "#...#"],
        "s": [".....", ".....", ".####", "#....", ".###.", "....#", "####."],
        "1": ["..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###."],
        "2": [".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####"],
        "3": [".###.", "#...#", "....#", "..##.", "....#", "#...#", ".###."],
        " ": ["...", "...", "...", "...", "...", "...", "..."]
    ]

    /// The text as rows of dots, `spacing` blank columns between letters. Unknown characters render as spaces.
    static func rows(for text: String, spacing: Int = 1) -> [String] {
        let letters = text.map { glyphs[$0] ?? glyphs[" "] ?? [] }
        let gap = String(repeating: ".", count: spacing)
        return (0..<height).map { row in
            letters.map { $0[row] }.joined(separator: gap)
        }
    }
}
